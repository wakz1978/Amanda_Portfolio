(VOLUNTEER_ID NUMBER(8),
  VOLUNTEER_LNAME VARCHAR(30) NOT NULL,
  VOLUNTEER_MIDDLENAME VARCHAR(20),
  VOLUNTEER_FNAME VARCHAR(30) NOT NULL,
  VOLUNTEER_STREETNO NUMBER(10),
  VOLUNTEER_STREET VARCHAR(20),
  VOLUNTEER_SUBURB VARCHAR(20),
  VOLUNTEER_COUNTRY VARCHAR(20),
  VOLUNTEER_POSTCODE NUMBER(8),
  VOLUNTEER_MOBILE_NO NUMBER(10) NOT NULL,
  VOLUNTEER_EMAIL VARCHAR(50) NOT NULL,
  VOLUNTEER_LANGUAGE VARCHAR(20) NOT NULL,
    CONSTRAINT V2_VOLUNTEER_PK
      PRIMARY KEY (VOLUNTEER_ID));

