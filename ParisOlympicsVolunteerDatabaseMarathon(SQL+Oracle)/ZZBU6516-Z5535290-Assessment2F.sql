/* Create Header Entity for Shift */

CREATE TABLE V2_SHIFT_HEADER
(SHIFT_ID NUMBER(8),
  SHIFT_DATE DATE NOT NULL,
  SHIFT_DAY VARCHAR(15) NOT NULL,
  SHIFT_STARTTIME NUMBER(2) NOT NULL,
  SHIFT_ENDTIME NUMBER(2) NOT NULL,
  ROLE_ID NUMBER(8),
  EVENT_ID NUMBER(8),
  STATION_ID VARCHAR(15),
    CONSTRAINT V2_SHIFT_HEADER_PK PRIMARY KEY (SHIFT_ID),
    CONSTRAINT V2_SHIFT_HEADER_FK FOREIGN KEY (STATION_ID)
      REFERENCES V2_STATION (STATION_ID),
     CONSTRAINT V2_SHIFT_HEADER_ROLE_ID_FK FOREIGN KEY (ROLE_ID)
      REFERENCES V2_ROLE(ROLE_ID),
    CONSTRAINT V2_SHIFT_HEADER_EVENT_ID_FK FOREIGN KEY (EVENT_ID)
      REFERENCES V2_EVENT(EVENT_ID)
);

