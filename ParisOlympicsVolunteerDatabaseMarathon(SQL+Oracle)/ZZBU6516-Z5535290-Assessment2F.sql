/*  Create entity for Availability Information  

    Links to Volunteer 
    
    Volunteer has one row for each day is available */

CREATE TABLE V2_AVAILABILITY
(VOLUNTEER_ID NUMBER(8),
  AVAILABILITY_LINENO NUMBER(2) ,
  AVAILABILITY_DATE DATE NOT NULL,
  AVAILABILITY_DAY VARCHAR(10) NOT NULL,
  AVAILABILITY_STARTTIME NUMBER(10) NOT NULL,
